"""Системные промпты и сборка контекста с явным указанием источника.

Формат блока контекста по заданию:
    Контекст 1 (Источник: Справочник_сотрудника_HR.pdf, стр. 4): <текст чанка>
Для Wiki вместо файла и страницы — название статьи:
    Контекст 2 (Источник: Wiki «Проект Atlas: …»): <текст чанка>

Готовая ссылка в нужном формате выписана прямо в заголовке блока
(«ссылка: [...]»): модели не нужно собирать её из частей — ей остаётся только
скопировать. Это снимает целый класс ошибок формата.
"""
from __future__ import annotations

from src.index import Hit

UNKNOWN = "Я не знаю"

SYSTEM_STRICT = f"""Ты — корпоративный ассистент компании РобоТех. Твоя задача — отвечать на вопросы сотрудников.

Правила:
1. Отвечай строго и только на основе предоставленного контекста. Не используй собственные знания, законы, «обычную практику» и догадки. Если ответа нет в тексте, напиши ровно: «{UNKNOWN}» — и больше ничего не добавляй.
2. Подтверждай каждый факт ссылкой на источник. Формат ссылки должен быть строго таким: [Название файла, стр. X] или [Название Wiki-статьи]. Ссылка ставится в конце того предложения или пункта списка, который она подтверждает. Каждый абзац и каждый пункт списка должен заканчиваться ссылкой.
3. Бери ссылку только из заголовка того блока контекста, откуда взят факт (поле «ссылка»). Номер страницы бери только оттуда. Числа внутри текста фрагмента не являются номерами страниц.
4. Никогда не придумывай файлы, страницы и статьи, которых нет в заголовках блоков контекста. Если факт подтверждают два блока, поставь обе ссылки: [A, стр. X][B, стр. Y].
5. Если вопрос требует сведений из нескольких документов, собери ответ из всех нужных блоков и сошлись на каждый.
6. Если документы противоречат друг другу, не выбирай молча: назови оба варианта со ссылками. Документ с пометкой «архив» описывает прошлые правила — так и скажи.
7. Если в контексте есть только часть ответа, ответь на эту часть со ссылками, а про недостающее напиши: «{UNKNOWN}, в базе знаний этого нет».
8. Отвечай по-русски, кратко и по делу."""

# Тот же набор требований в минимальной формулировке — для сравнения.
SYSTEM_BASIC = f"""Ты — корпоративный ассистент. Твоя задача — отвечать на вопросы сотрудников.
Отвечай строго и только на основе предоставленного контекста. Если ответа нет в тексте, напиши '{UNKNOWN}'.
Подтверждай каждый факт ссылкой на источник. Формат ссылки должен быть строго таким: [Название файла, стр. X] или [Название Wiki-статьи]."""

SYSTEMS = {"strict": SYSTEM_STRICT, "basic": SYSTEM_BASIC}


def source_label(hit: Hit) -> str:
    m = hit.meta
    if m["doc_type"] == "pdf" and not m["page"]:
        return m["source"]                     # naive: страница неизвестна
    if m["doc_type"] == "pdf":
        return f"{m['source']}, стр. {m['page']}"
    return f"Wiki «{m['title']}»"


def format_context(hits: list[Hit], with_ref: bool = True) -> str:
    blocks = []
    for i, h in enumerate(hits, 1):
        head = f"Контекст {i} (Источник: {source_label(h)}"
        if h.meta.get("header") and h.meta["header"] != h.meta.get("title"):
            head += f"; раздел «{h.meta['header']}»"
        if with_ref:
            head += f"; ссылка: {h.ref()}"
        blocks.append(f"{head}):\n{h.text}")
    return "\n\n".join(blocks)


def build_messages(question: str, hits: list[Hit], system: str = "strict",
                   answer_style: str = "", with_ref: bool = True) -> list[dict]:
    user = (f"{format_context(hits, with_ref=with_ref)}\n\n---\nВопрос сотрудника: {question}"
            + (f"\n{answer_style}" if answer_style else ""))
    return [{"role": "system", "content": SYSTEMS.get(system, system)},
            {"role": "user", "content": user}]
